  Widget _avatar(String initials, ProfileController controller) {
    return GestureDetector(
      onTap: () => controller.pickAndUploadProfileImage(),
      child: Obx(() {
        // Show upload indicator
        if (controller.isUploadingImage.value) {
          return _uploadingIndicator();
        }

        // Check if profileImage URL is valid
        final hasValidImage = controller.user.value?.profileImage != null &&
            controller.user.value!.profileImage!.isNotEmpty &&
            _isValidUrl(controller.user.value!.profileImage!);

        // Show image or fallback
        if (hasValidImage) {
          return _networkImageAvatar(
            controller.user.value!.profileImage!,
            initials,
            controller,
          );
        } else {
          return _fallbackAvatar(initials);
        }
      }),
    );
  }

  // Network image avatar with camera icon overlay
  Widget _networkImageAvatar(
    String imageUrl,
    String initials,
    ProfileController controller,
  ) {
    return Obx(() {
      // Get refresh timestamp from controller - updates on every pull-to-refresh
      final refreshTimestamp = controller.imageRefreshTimestamp.value;
      
      // Add cache-busting parameter using refresh timestamp
      // This ensures image is reloaded from backend on every pull-to-refresh
      // even if the URL is the same but image content has changed
      final cacheBustedUrl = _addCacheBusterWithTimestamp(imageUrl, refreshTimestamp);
      
      return Stack(
        children: [
          Container(
            width: 64,
            height: 64,
            decoration: BoxDecoration(
              shape: BoxShape.circle,
              border: Border.all(
                color: AppColors.brandSage500.withValues(alpha: 0.3),
                width: 2,
              ),
            ),
            child: ClipOval(
              // Use Key with refresh timestamp to force rebuild on every refresh
              // This ensures CachedNetworkImage reloads even if URL is the same
              key: ValueKey('$imageUrl-$refreshTimestamp'),
              child: CachedNetworkImage(
                imageUrl: cacheBustedUrl,
                fit: BoxFit.cover,
                placeholder: (context, url) => Container(
                  color: AppColors.brandSage500.withValues(alpha: 0.1),
                  child: Center(
                    child: CircularProgressIndicator(
                      strokeWidth: 2,
                      valueColor: AlwaysStoppedAnimation<Color>(
                        AppColors.brandSage500,
                      ),
                    ),
                  ),
                ),
                errorWidget: (context, url, error) => _fallbackAvatar(initials),
              ),
            ),
          ),
        // Camera icon overlay
        Positioned(
          bottom: 0,
          right: 0,
          child: Container(
            width: 20,
            height: 20,
            decoration: BoxDecoration(
              color: AppColors.brandSage500,
              shape: BoxShape.circle,
              border: Border.all(color: Colors.white, width: 2),
            ),
            child: const Icon(
              Icons.camera_alt,
              size: 10,
              color: Colors.white,
            ),
          ),
        ),
        ],
      );
    });
  }

